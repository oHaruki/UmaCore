"""
Static game data for the skill maps: skills, courses, graded races and support
card skill hints, loaded once from assets/gamedata.json.

That file is generated by scripts/build_skillmap_data.py from the Global
client's master.mdb; rerun it after a game update.
"""
from __future__ import annotations

import json
import re
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Optional

DATA_FILE = Path(__file__).parent / "assets" / "gamedata.json"

SURFACES = {1: "Turf", 2: "Dirt"}
TURNS = {1: "Right-handed", 2: "Left-handed", 4: "Straight"}
INOUT = {2: "Inner", 3: "Outer", 4: "Outer→Inner"}
DISTANCE_TYPES = {1: "Sprint", 2: "Mile", 3: "Medium", 4: "Long"}
SEASONS = {1: "Spring", 2: "Summer", 3: "Fall", 4: "Winter", 5: "Spring"}
WEATHERS = {1: "Sunny", 2: "Cloudy", 3: "Rainy", 4: "Snowy"}
GROUNDS = {1: "Firm", 2: "Good", 3: "Soft", 4: "Heavy"}
STRATEGIES = {1: "Front Runner", 2: "Pace Chaser", 3: "Late Surger", 4: "End Closer"}
GRADES = {100: "G1", 200: "G2", 300: "G3"}

# Effect kinds (ability_type) and targets (target_type) used by the analysis.
ACCEL, TARGET_SPEED, CURRENT_SPEED, CURRENT_SPEED_DECEL, RECOVERY = 31, 27, 21, 22, 9
STAT_UPS = {1: "Speed", 2: "Stamina", 3: "Power", 4: "Guts", 5: "Wit"}
TARGET_SELF = 1


def distance_type(distance: int) -> int:
    if distance <= 1400:
        return 1
    if distance <= 1800:
        return 2
    if distance < 2500:
        return 3
    return 4


@dataclass(frozen=True)
class Course:
    id: int
    track_id: int
    track: str
    distance: int
    surface: int
    turn: int
    inout: int
    stats: tuple            # course bonus stats (1 Speed .. 5 Wit)
    corners: tuple          # ((start, end), ...) in race order
    straights: tuple        # ((start, end, front_type), ...)
    slopes: tuple           # ((start, end, percent), ...), negative = downhill

    @property
    def distance_type(self) -> int:
        return distance_type(self.distance)

    @property
    def label(self) -> str:
        side = f" ({INOUT[self.inout]})" if self.inout in INOUT else ""
        return f"{self.track} {self.distance}m {SURFACES.get(self.surface, '')}{side}"


@dataclass(frozen=True)
class RaceEnv:
    season: int = 1
    weather: int = 1
    ground: int = 1
    time: int = 2          # midday
    grade: int = 100

    @property
    def label(self) -> str:
        return f"{GROUNDS.get(self.ground, '?')} · {WEATHERS.get(self.weather, '?')} · {SEASONS.get(self.season, '?')}"


@dataclass(frozen=True)
class Effect:
    kind: int
    value: float
    target: int


@dataclass(frozen=True)
class Alternative:
    pre: str
    cond: str
    duration: float        # base seconds, scaled by distance/1000 in a race; <0 = whole race
    cooldown: float
    effects: tuple


@dataclass(frozen=True)
class Skill:
    id: int
    name: str
    desc: str
    rarity: int
    wit_check: bool
    sp: Optional[int]
    alts: tuple
    group: int = 0
    grade: int = 0
    icon: int = 0

    @property
    def is_unique(self) -> bool:
        return self.rarity >= 3

    @property
    def is_negative(self) -> bool:
        """The × versions: every effect on the runner is a penalty."""
        effects = self.self_effects()
        return bool(effects) and all(e.value < 0 for e in effects)

    @property
    def icon_url(self) -> Optional[str]:
        if not self.icon:
            return None
        return f"https://gametora.com/images/umamusume/skill_icons/utx_ico_skill_{self.icon}.png"

    @property
    def rarity_label(self) -> str:
        if self.rarity >= 3:
            return "Unique"
        if self.id >= 900_000:
            return "Inherited unique"
        return "Gold" if self.rarity == 2 else "White"

    def self_effects(self) -> list:
        return [e for a in self.alts for e in a.effects if e.target == TARGET_SELF]

    def has_effect(self, kind: int) -> bool:
        return any(e.kind == kind and e.value > 0 for e in self.self_effects())


@dataclass(frozen=True)
class SupportCard:
    id: int
    title: str
    chara: str
    rarity: int            # 1 R, 2 SR, 3 SSR
    kind: str              # Speed, Stamina, Power, Guts, Wit, Friend, Group
    hints: tuple           # skill ids the card can hint

    @property
    def rarity_label(self) -> str:
        return {1: "R", 2: "SR", 3: "SSR"}.get(self.rarity, "")


@dataclass(frozen=True)
class Race:
    id: int
    name: str
    course_id: int
    grade: int


def _fold(text: str) -> str:
    """Lower-case, strip accents and symbols, for forgiving name search."""
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


@dataclass(frozen=True)
class CourseChoice:
    key: str               # "cm:champions-meeting-20", "race:1023", "course:10808"
    label: str
    course: Course
    env: RaceEnv
    event: str = ""        # Champions Meeting name, e.g. "Capricorn Cup"


class GameData:
    def __init__(self, raw: dict):
        self.built = raw.get("built", "")
        self.skills = {}
        for sid, s in raw["skills"].items():
            alts = tuple(
                Alternative(a["pre"], a["cond"], a["dur"], a["cd"],
                            tuple(Effect(int(k), float(v), int(t)) for k, v, t in a["eff"]))
                for a in s["alts"]
            )
            self.skills[int(sid)] = Skill(int(sid), s["n"], s["d"], s["r"], bool(s["lot"]), s["sp"], alts,
                                          s.get("g", 0), s.get("gv", 0), s.get("icon", 0))
        self.courses = {
            int(cid): Course(
                int(cid), c["track"], c["name"], c["dist"], c["surf"], c["turn"], c["inout"], tuple(c["stats"]),
                tuple(tuple(x) for x in c["corners"]), tuple(tuple(x) for x in c["straights"]),
                tuple(tuple(x) for x in c["slopes"]),
            )
            for cid, c in raw["courses"].items()
        }
        self.races = [Race(r["id"], r["name"], r["course"], r["grade"]) for r in raw["races"]]
        self.cards = {
            int(cid): SupportCard(int(cid), c["t"], c["c"], c["r"], c["k"], tuple(c["h"]))
            for cid, c in raw.get("cards", {}).items()
        }
        self._hinted_by: dict = {}
        for card in sorted(self.cards.values(), key=lambda c: (-c.rarity, c.chara, c.title)):
            for sid in card.hints:
                self._hinted_by.setdefault(sid, []).append(card)
        self._skill_index = sorted(((_fold(s.name), s) for s in self.skills.values()), key=lambda p: p[1].name)

    # ── skills ──────────────────────────────────────────────────────────────

    def search_skills(self, query: str, limit: int = 25) -> list:
        q = _fold(query)
        if not q:
            return [s for _, s in self._skill_index[:limit]]
        starts, contains = [], []
        for folded, skill in self._skill_index:
            if folded.startswith(q):
                starts.append(skill)
            elif q in folded:
                contains.append(skill)
        return (starts + contains)[:limit]

    def find_skill(self, value: str) -> Optional[Skill]:
        value = value.strip()
        if value.isdigit() and int(value) in self.skills:
            return self.skills[int(value)]
        # Exact name first: folding drops ○/◎/×, which tell variants apart.
        raw = value.casefold()
        for _, skill in self._skill_index:
            if skill.name.casefold() == raw:
                return skill
        q = _fold(value)
        exact = [s for folded, s in self._skill_index if folded == q]
        if exact:
            return exact[0]
        found = self.search_skills(value, limit=1)
        return found[0] if found else None

    def cards_for(self, skill_id: int) -> list:
        """Support cards that can hint the skill, best rarity first."""
        return list(self._hinted_by.get(skill_id, []))

    def related(self, skill: Skill) -> tuple:
        """(weaker, stronger) version of the same skill, e.g. Head-On / Neck and Neck."""
        if skill.is_unique or skill.id >= 900_000 or not skill.group:
            return None, None
        family = sorted((s for s in self.skills.values()
                         if s.group == skill.group and not s.is_unique and not s.is_negative and s.id < 900_000),
                        key=lambda s: (s.rarity, s.grade))
        if skill not in family:
            return None, None
        i = family.index(skill)
        return (family[i - 1] if i > 0 else None), (family[i + 1] if i + 1 < len(family) else None)

    # ── courses ─────────────────────────────────────────────────────────────

    def course_choices(self, query: str = "", limit: int = 25, cms=()) -> list:
        """Autocomplete entries: the given Champions Meetings first, then races and courses."""
        q = _fold(query)
        out = [cm for cm in cms if not q or q in _fold(cm.label) or q in ("cm", "champions meeting")]
        for race in self.races:
            course = self.courses[race.course_id]
            label = f"{race.name} ({GRADES.get(race.grade, '')}) - {course.label}"
            if q and q in _fold(label):
                out.append(CourseChoice(f"race:{race.id}", label, course, RaceEnv()))
        for course in sorted(self.courses.values(), key=lambda c: (c.track, c.surface, c.distance, c.inout)):
            if not q or all(part in _fold(course.label) for part in q.split()):
                out.append(CourseChoice(f"course:{course.id}", course.label, course, RaceEnv()))
        return out[:limit]

    def resolve_course(self, value: Optional[str], cms=()) -> Optional[CourseChoice]:
        """A picked autocomplete value, free text, or (when empty) the first of ``cms``."""
        if not value:
            return cms[0] if cms else None
        for cm in cms:
            if cm.key == value:
                return cm
        kind, _, ident = value.partition(":")
        if ident.isdigit():
            n = int(ident)
            if kind == "race":
                race = next((r for r in self.races if r.id == n), None)
                if race:
                    course = self.courses[race.course_id]
                    return CourseChoice(value, f"{race.name} - {course.label}", course, RaceEnv())
            elif kind == "course" and n in self.courses:
                course = self.courses[n]
                return CourseChoice(value, course.label, course, RaceEnv())
        if kind == "cm":
            return None     # a Champions Meeting that has since dropped off the schedule
        # Free text typed without picking an autocomplete entry.
        matches = self.course_choices(value, limit=1, cms=cms)
        return matches[0] if matches else None


@lru_cache(maxsize=1)
def load() -> GameData:
    return GameData(json.loads(DATA_FILE.read_text(encoding="utf-8")))
